-- Run manually in the existing inventory database using SQL Server Management Studio.
-- No database or inventory tables are created or changed by this script.
SET XACT_ABORT ON;
BEGIN TRANSACTION;

IF OBJECT_ID(N'dbo.app_users', N'U') IS NULL
BEGIN
    CREATE TABLE dbo.app_users (
        id INT IDENTITY(1,1) NOT NULL CONSTRAINT PK_app_users PRIMARY KEY,
        username NVARCHAR(100) COLLATE Latin1_General_100_CI_AS NOT NULL,
        display_name NVARCHAR(150) NOT NULL,
        password_hash VARCHAR(200) NOT NULL,
        is_active BIT NOT NULL CONSTRAINT DF_app_users_is_active DEFAULT (1),
        is_admin BIT NOT NULL CONSTRAINT DF_app_users_is_admin DEFAULT (0),
        created_at DATETIME2(3) NOT NULL CONSTRAINT DF_app_users_created_at DEFAULT (SYSUTCDATETIME()),
        CONSTRAINT UQ_app_users_username UNIQUE (username)
    );
END;

IF OBJECT_ID(N'dbo.user_sessions', N'U') IS NULL
BEGIN
    CREATE TABLE dbo.user_sessions (
        token_hash CHAR(64) NOT NULL CONSTRAINT PK_user_sessions PRIMARY KEY,
        user_id INT NOT NULL,
        expires_at DATETIME2(3) NOT NULL,
        created_at DATETIME2(3) NOT NULL CONSTRAINT DF_user_sessions_created_at DEFAULT (SYSUTCDATETIME()),
        CONSTRAINT FK_user_sessions_user FOREIGN KEY (user_id) REFERENCES dbo.app_users(id) ON DELETE CASCADE
    );
    CREATE INDEX IX_user_sessions_expires_at ON dbo.user_sessions(expires_at);
    CREATE INDEX IX_user_sessions_user_id ON dbo.user_sessions(user_id);
END;

COMMIT TRANSACTION;

